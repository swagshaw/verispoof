// ------------------------------------------------------------------ counters
function countUp() {
  $$(".stat b[data-count]").forEach((el) => {
    const target = parseFloat(el.dataset.count), dec = +el.dataset.dec, suf = el.dataset.suffix || "";
    if (reduced) return;
    const t0 = performance.now(), D = 1300;
    const step = (now) => {
      const k = Math.min(1, (now - t0) / D), e = 1 - Math.pow(1 - k, 3);
      el.textContent = (target * e).toFixed(dec) + suf;
      if (k < 1) requestAnimationFrame(step);
    };
    requestAnimationFrame(step);
  });
}

// ------------------------------------------------------------------ hero: a row of 0.16 s tokens, one span lights up
let heroProf = null;
function heroDraw(now) {
  const cv = $("#heroTokens"); if (!cv) return;
  const dpr = window.devicePixelRatio || 1, W = cv.clientWidth, H = cv.clientHeight;
  if (!W) return;
  if (cv.width !== Math.round(W * dpr)) { cv.width = Math.round(W * dpr); cv.height = Math.round(H * dpr); }
  const g = cv.getContext("2d"); g.setTransform(dpr, 0, 0, dpr, 0, 0); g.clearRect(0, 0, W, H);
  const n = Math.max(40, Math.floor(W / 14)), bw = W / n;
  if (!heroProf || heroProf.length !== n) heroProf = Array.from({ length: n }, (_, i) => 0.25 + 0.55 * Math.abs(Math.sin(i * 1.7) * Math.cos(i * 0.37)));
  const t = reduced ? 0 : now / 1000, c = ((t * 0.08) % 1.4 - 0.2) * n;
  const line = css("--line2"), syn = css("--synth");
  for (let i = 0; i < n; i++) {
    const hot = Math.max(0, 1 - Math.abs(i - c) / 5);
    const h = (heroProf[i] * 0.55 + hot * 0.45) * (H - 10);
    g.fillStyle = hot > 0.15 ? syn : line;
    g.globalAlpha = hot > 0.15 ? 0.25 + 0.6 * hot : 0.7;
    g.fillRect(i * bw + 2, H - h, bw - 4, h);
  }
  g.globalAlpha = 1;
}
function heroLoop(now) { heroDraw(now); if (!reduced) requestAnimationFrame(heroLoop); }

// ------------------------------------------------------------------ spectrogram tinting
const tintCache = new Map(), imgCache = new Map();
function loadImg(src) {
  if (!imgCache.has(src)) {
    const im = new Image();
    im.onload = () => { tintCache.clear(); drawExample(audioT("ex")); drawPairCanvases(); };
    im.src = src;
    imgCache.set(src, im);
  }
  return imgCache.get(src);
}
function tinted(src, color) {
  const key = src + color, im = loadImg(src);
  if (!im.complete || !im.naturalWidth) return null;
  if (!tintCache.has(key)) {
    const c = document.createElement("canvas"); c.width = im.naturalWidth; c.height = im.naturalHeight;
    const g = c.getContext("2d"); g.drawImage(im, 0, 0); g.globalCompositeOperation = "source-in";
    g.fillStyle = color; g.fillRect(0, 0, c.width, c.height);
    tintCache.set(key, c);
  }
  return tintCache.get(key);
}

// ------------------------------------------------------------------ audio
function audioT(kind) { return playing && playing.kind === kind ? audio.currentTime : (kind === "ex" ? exT : 0); }
let exT = 0;
function playSrc(kind, src, btn, from = null) {
  if (playing && playing.kind === kind && !audio.paused) { stopAudio(); return; }
  stopAudio();
  if (!audio.src.endsWith(src)) audio.src = src;
  if (from !== null) audio.currentTime = from;
  else if (audio.ended || (kind === "ex" && exT >= EX.examples[cur].dur - 0.05)) audio.currentTime = 0;
  playing = { kind, btn };
  btn.textContent = "❚❚"; btn.setAttribute("aria-label", "Pause");
  audio.play().catch(() => stopAudio());
  const loop = () => {
    if (kind === "ex") { exT = audio.currentTime; drawExample(exT); } else drawPairCanvases();
    if (!audio.paused) raf = requestAnimationFrame(loop);
  };
  raf = requestAnimationFrame(loop);
}
function stopAudio() {
  audio.pause(); cancelAnimationFrame(raf);
  if (playing) { playing.btn.textContent = "▶"; playing.btn.setAttribute("aria-label", "Play"); }
  const was = playing; playing = null;
  if (was && was.kind === "ex") drawExample(exT); else drawPairCanvases();
}
audio.addEventListener("ended", () => { if (playing && playing.kind === "ex") exT = EX.examples[cur].dur; stopAudio(); });

