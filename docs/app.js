let sortCol = null, sortAsc = true;
function setTable() {
  const B = BENCH, cols = [...B.sets, "Mean", "Pooled"];
  const val = (r, c) => (c === "Mean" ? r.mean : c === "Pooled" ? r.pooled : r.sets[B.sets.indexOf(c)]);
  const best = Object.fromEntries(cols.map((c) => [c, Math.min(...B.table.map((r) => val(r, c)).filter((v) => v !== null))]));
  let body = "";
  const rowHTML = (r) => `<tr class="${r.kind === "ours" ? "ours" : ""}"><td>${esc(r.name)}${r.spoofradar_only ? " ‡" : ""}</td>` +
    cols.map((c) => { const v = val(r, c); return `<td class="${v === null ? "na" : v === best[c] ? "best" : ""}">${v === null ? "–" : v.toFixed(2)}</td>`; }).join("") + "</tr>";
  if (sortCol === null) {
    [["proprietary", "Proprietary"], ["open", "Open weights"], ["ours", "Ours"]].forEach(([k, name]) => {
      body += `<tr><td class="grp" colspan="${cols.length + 1}">${name}</td></tr>` + B.table.filter((r) => r.kind === k).map(rowHTML).join("");
    });
  } else {
    const rs = B.table.slice().sort((a, b) => {
      const va = val(a, sortCol), vb = val(b, sortCol);
      if (va === null) return 1; if (vb === null) return -1;
      return sortAsc ? va - vb : vb - va;
    });
    body = rs.map(rowHTML).join("");
  }
  $("#setTable").innerHTML = `<thead><tr><th data-c="" title="Group by availability">System</th>${cols.map((c) =>
    `<th data-c="${c}" class="${c === sortCol ? "sorted" : ""}" title="${esc(B.set_names[c] || c + " EER")}">${c}${c === sortCol ? (sortAsc ? " ▲" : " ▼") : ""}</th>`).join("")}</tr></thead><tbody>${body}</tbody>`;
  $$("#setTable th").forEach((th) => th.addEventListener("click", () => {
    const c = th.dataset.c || null;
    if (c === sortCol && c !== null) sortAsc = !sortAsc; else { sortCol = c; sortAsc = true; }
    setTable();
  }));
}
