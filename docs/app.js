function drawPairCanvases() {
  if (!EX) return;
  const p = EX.pairs[curPair];
  $$("#pairAudio canvas").forEach((cv) => {
    const k = cv.dataset.k, s = p[k], dpr = window.devicePixelRatio || 1, W = cv.clientWidth, H = cv.clientHeight;
    if (!W) return;
    if (cv.width !== Math.round(W * dpr)) { cv.width = Math.round(W * dpr); cv.height = Math.round(H * dpr); }
    const g = cv.getContext("2d"); g.setTransform(dpr, 0, 0, dpr, 0, 0); g.clearRect(0, 0, W, H);
    const im = tinted(s.spec, css("--text"));
    if (im) { g.globalAlpha = 0.8; g.drawImage(im, 0, 0, W, H); g.globalAlpha = 1; }
    if (playing && playing.kind === "p" + k) {
      const xx = (audio.currentTime / s.dur) * W;
      g.strokeStyle = css("--synth"); g.lineWidth = 2; g.beginPath(); g.moveTo(xx, 0); g.lineTo(xx, H); g.stroke();
    }
  });
}

