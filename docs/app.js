function dumbbell(box, rows, lo, keyA, keyB) {
  const X = (v) => Math.max(0, Math.min(100, (100 * (v - lo)) / (100 - lo)));
  box.innerHTML = rows.map((r) => {
    const a = r[keyA], b = r[keyB], l = Math.min(X(a), X(b)), w = Math.abs(X(b) - X(a));
    return `<div class="db ${b - a >= 5 ? "hot" : ""}" title="${esc(r.set)}: ${a.toFixed(1)} → ${b.toFixed(1)}"><span class="nm">${esc(r.set)}</span>
      <span class="ln"><span class="rail"></span><span class="seg2" style="left:${l}%;width:${w}%"></span><span class="p a" style="left:${X(a)}%"></span><span class="p b" style="left:${X(b)}%"></span></span>
      <span class="v">${a.toFixed(1)} → <b>${b.toFixed(1)}</b></span></div>`;
  }).join("") + `<div class="db" aria-hidden="true"><span></span><span class="ln" style="height:12px"><small style="position:absolute;left:0;font:11px var(--mono);color:var(--faint)">${lo}</small><small style="position:absolute;right:0;font:11px var(--mono);color:var(--faint)">100</small></span><span></span></div>`;
}
