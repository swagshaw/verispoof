function decWord(d) { return d === "spoof" ? "Spoof" : d === "bonafide" ? "Genuine" : "No decision"; }
function verdictBadge(ok) { return `<span class="badge ${ok ? "ok" : "fail"}">${ok ? "✓ correct" : "✗ wrong"}</span>`; }

function renderModel() {
  const e = EX.examples[cur], m = e.models[model], lab = e.gold.label;
  const p = m.p_spoof;
  $("#pBar").style.width = (100 * p).toFixed(1) + "%";
  $("#pVal").textContent = `P(spoof) ${p.toFixed(2)} · s ${m.score >= 0 ? "+" : ""}${m.score.toFixed(2)}`;
  const dOk = m.direct === lab, rOk = m.decision === lab;
  $("#directVerdict").innerHTML = `${decWord(m.direct)} ${verdictBadge(dOk)}`;
  $("#reasonVerdict").innerHTML = `${decWord(m.decision)} ${verdictBadge(rOk)}`;
  const co = $("#callout");
  let msg = "";
  if (!dOk && rOk) msg = e.gold.kind === "partial"
    ? "The one-step answer misses this partial fake. The rationale localizes the synthetic span, and the decision that follows from it is correct."
    : "The one-step answer gets this recording wrong; the decision reached after the rationale is right.";
  else if (dOk && !rOk) msg = "Here the one-step answer is right and the rationale is not.";
  else if (!dOk && !rOk) msg = "Both the one-step answer and the rationale get this one wrong.";
  co.hidden = !msg; co.textContent = msg;
  const f = m.flip;
  $("#cf").innerHTML = `<h5>Counterfactual test</h5><p>Replace the stated LOCALIZATION with <code>${esc(f.edited)}</code> and let the model decide again:</p>
    <p><b style="color:var(--text)">${decWord(f.decision)}</b> <span class="badge ${f.follows ? "ok" : "fail"}">${f.follows ? "✓ follows the edit" : "✗ ignores the edit"}</span></p>`;
  $("#ratModel").textContent = "· " + MODEL_NAME[model];
  renderRows($("#rows"), $("#tally"), m.checks);
  $("#rawText").textContent = m.text;
  $("#tileNote").textContent = e.gold.tiled
    ? `The model hears an 8 s window; this ${e.dur.toFixed(1)} s recording is looped to fill it, so stated times refer to its first occurrence (the rationale also states the recording's length). Checks: observations against measurements on that window (SNR within 10 dB, level within 5 dB), localization by time overlap (IoU ≥ 0.5), source profile against generator metadata.`
    : "";
  drawExample(exT);
}

function itemHTML(it) {
  const x = it.status === "ok" ? "✓" : it.status === "fail" ? "✗" : "◐";
  const same = it.said.replace("both ", "") === it.ref || it.said === it.ref;
  if (same) return `<span class="it ${it.status}"><span class="x">${x}</span>${esc(it.item)}: <b>${esc(it.said)}</b> · matches metadata</span>`;
  return `<span class="it ${it.status}"><span class="x">${x}</span>${esc(it.item)}: <b>${esc(it.said)}</b> · ${it.status === "ok" ? "" : "ref "}${esc(it.ref)}${it.tol ? ` <small>(${esc(it.tol)})</small>` : ""}</span>`;
}
function renderRows(box, tallyBox, checks) {
  const n = { ok: 0, fail: 0, partial: 0, na: 0 };
  checks.forEach((c) => n[c.status]++);
  tallyBox.innerHTML = ["ok", "fail", "partial", "na"].filter((k) => n[k]).map((k) =>
    `<span class="badge ${k}" title="${{ ok: "lines that hold", fail: "lines that fail", partial: "lines that partly hold", na: "lines without an external reference" }[k]}">${{ ok: "✓", fail: "✗", partial: "◐", na: "–" }[k]} ${n[k]}</span>`).join("");
  box.innerHTML = checks.map((c) => {
    const dec = c.field === "DECISION";
    const label = dec ? (c.status === "ok" ? "✓ correct" : "✗ wrong") : BADGE[c.status];
    const items = c.items && c.items.length ? `<span class="items">${c.items.map(itemHTML).join("")}</span>` : "";
    const ref = c.ref && !(c.items && c.items.length && c.field === "OBSERVATIONS") ? `<span class="ref">${esc(c.ref)}</span>` : "";
    return `<div class="row${dec ? " dec" : ""}"><span class="f">${c.field}</span><span class="s">${esc(c.text)}${ref}${items}</span>
      <span class="badge ${c.status}" title="checked ${esc(c.how || "")}">${label}</span></div>`;
  }).join("");
}

// spectrogram + spans + per-token probabilities
const G = { L: 30, R: 10, T: 26 };
function exLayout(W, H) {
  const specTop = G.T, specH = Math.round((H - G.T - 22) * 0.58), tokTop = specTop + specH + 22, tokH = H - 22 - tokTop;
  return { specTop, specH, tokTop, tokH };
}
function drawExample(t) {
  if (!EX) return;
  const e = EX.examples[cur], m = e.models[model], cv = $("#specCanvas");
  const dpr = window.devicePixelRatio || 1, W = cv.clientWidth, H = cv.clientHeight;
  if (!W) return;
  if (cv.width !== Math.round(W * dpr) || cv.height !== Math.round(H * dpr)) { cv.width = Math.round(W * dpr); cv.height = Math.round(H * dpr); }
  const g = cv.getContext("2d"); g.setTransform(dpr, 0, 0, dpr, 0, 0); g.clearRect(0, 0, W, H);
  const D = e.dur, x = (s) => G.L + (s / D) * (W - G.L - G.R);
  const { specTop, specH, tokTop, tokH } = exLayout(W, H);
  const text = css("--text"), muted = css("--muted"), faint = css("--faint"), syn = css("--synth"), line = css("--line2"), lab = css("--label");
  // spectrogram
  const im = tinted(e.spec, text);
  if (im) { g.globalAlpha = 0.82; g.drawImage(im, G.L, specTop, W - G.L - G.R, specH); g.globalAlpha = 1; }
  g.font = "10px 'IBM Plex Mono', monospace"; g.fillStyle = faint; g.textAlign = "right";
  g.fillText("8k", G.L - 5, specTop + 8); g.fillText("4k", G.L - 5, specTop + specH / 2 + 3); g.fillText("0", G.L - 5, specTop + specH);
  g.textAlign = "left";
  // labelled spans: hatched; a fully synthesized recording gets a bar instead
  const hatch = (a, b, y0, h) => {
    g.save(); g.beginPath(); g.rect(x(a), y0, x(b) - x(a), h); g.clip();
    g.strokeStyle = lab; g.globalAlpha = 0.35; g.lineWidth = 1;
    for (let k = x(a) - h; k < x(b) + h; k += 7) { g.beginPath(); g.moveTo(k, y0 + h); g.lineTo(k + h, y0); g.stroke(); }
    g.restore();
    g.strokeStyle = lab; g.lineWidth = 1.5; g.beginPath(); g.moveTo(x(a), y0); g.lineTo(x(a), y0 + h); g.moveTo(x(b), y0); g.lineTo(x(b), y0 + h); g.stroke();
  };
  g.font = "600 10.5px 'IBM Plex Mono', monospace";
  const pill = (txt, px, col) => {
    const w = g.measureText(txt).width + 10, y = specTop + specH - 18;
    px = Math.max(G.L + 2, Math.min(px, W - G.R - w - 2));
    g.fillStyle = css("--card"); g.globalAlpha = 0.92; g.fillRect(px, y, w, 15); g.globalAlpha = 1;
    g.fillStyle = col; g.fillText(txt, px + 5, y + 11);
  };
  if (e.gold.kind === "partial") {
    e.gold.spans.forEach(([a, b]) => hatch(a, Math.min(b, D), specTop, specH));
    pill("labelled span", x(e.gold.spans[0][0]) + 3, lab);
  } else pill(e.gold.label === "spoof" ? "label: fully synthesized" : "label: genuine", G.L + 2, e.gold.label === "spoof" ? lab : muted);
  // spans stated by the model
  const stated = m.spans && m.spans.length ? m.spans : (/whole recording is synthesized/.test(m.text) ? [[0, D]] : []);
  stated.forEach(([a, b]) => {
    b = Math.min(b, D); if (a >= D) return;
    g.fillStyle = syn; g.globalAlpha = 0.16; g.fillRect(x(a), specTop, x(b) - x(a), specH); g.globalAlpha = 1;
    g.fillRect(x(a), specTop - 4, x(b) - x(a), 3);
  });
  if (stated.length) {
    const a = stated[0][0], whole = stated.length === 1 && stated[0][0] === 0 && stated[0][1] >= D;
    g.fillStyle = syn; g.textAlign = whole ? "right" : "left";
    const lbl = whole ? "stated: whole recording" : `stated: ${stated.map(([p, q]) => `${p.toFixed(2)}–${q.toFixed(2)} s`).join(", ")}`;
    g.fillText(lbl, whole ? W - G.R : Math.min(x(a), W - G.R - g.measureText(lbl).width), specTop - 9);
    g.textAlign = "left";
  } else if (m.decision) {
    g.fillStyle = muted; g.textAlign = "right"; g.fillText("stated: no synthesized segment", W - G.R, specTop - 10); g.textAlign = "left";
  }
  // per-token probabilities (first occurrence of the recording only)
  const step = m.token_seconds, P = m.token_prob;
  g.strokeStyle = line; g.lineWidth = 1; g.setLineDash([3, 3]);
  g.beginPath(); g.moveTo(G.L, tokTop + tokH / 2); g.lineTo(W - G.R, tokTop + tokH / 2); g.stroke(); g.setLineDash([]);
  g.fillStyle = faint; g.font = "10px 'IBM Plex Mono', monospace"; g.textAlign = "right";
  g.fillText("1", G.L - 5, tokTop + 8); g.fillText(".5", G.L - 5, tokTop + tokH / 2 + 3); g.fillText("0", G.L - 5, tokTop + tokH);
  g.textAlign = "left";
  for (let i = 0; i < P.length && i * step < D; i++) {
    const a = i * step, b = Math.min(D, (i + 1) * step), p = P[i], h = Math.max(1.5, p * tokH);
    g.fillStyle = p >= 0.5 ? syn : line; g.globalAlpha = p >= 0.5 ? 0.55 + 0.45 * p : 0.9;
    g.fillRect(x(a) + 1, tokTop + tokH - h, Math.max(1, x(b) - x(a) - 2), h);
  }
  g.globalAlpha = 1;
  g.fillStyle = muted; g.fillText("P(synthetic) per 0.16 s token", G.L, tokTop - 7);
  // played region and playhead
  if (t > 0) {
    g.strokeStyle = text; g.lineWidth = 1.5; g.beginPath(); g.moveTo(x(Math.min(t, D)), specTop - 2); g.lineTo(x(Math.min(t, D)), tokTop + tokH + 3); g.stroke();
  }
  // time axis
  g.fillStyle = faint; g.font = "10px 'IBM Plex Mono', monospace";
  const tick = D > 6 || W < 500 ? 1 : 0.5;
  for (let s = 0; s <= D + 1e-6; s += tick) {
    const px = x(s); g.textAlign = s === 0 ? "left" : px > W - 30 ? "right" : "center";
    g.fillText(s.toFixed(tick < 1 ? 1 : 0) + (s === 0 ? " s" : ""), px, H - 6);
  }
  g.textAlign = "left";
  $("#tnow").textContent = Math.min(t, D).toFixed(2);
}

